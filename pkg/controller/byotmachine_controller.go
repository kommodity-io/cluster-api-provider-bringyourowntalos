const (
	// byotMachineFinalizer protects ByotMachine resources during deletion.
	byotMachineFinalizer = "byotmachine.infrastructure.cluster.x-k8s.io"

	// bootstrapSecretDataKey is the key holding the Talos machine
	// configuration in the bootstrap data secret.
	bootstrapSecretDataKey = "value"

	// clusterTalosConfigSecretSuffix is the suffix of the secret holding the
	// cluster's talosconfig, generated by the Talos bootstrap provider.
	clusterTalosConfigSecretSuffix = "-talosconfig" //nolint:gosec // Not a credential: file name suffix.

	// talosConfigSecretDataKey is the key holding the talosconfig document in
	// talosconfig secrets.
	talosConfigSecretDataKey = "talosconfig"

	// requeueAfterBootstrap is the delay used while waiting for bootstrap data.
	requeueAfterBootstrap = 10 * time.Second

	// requeueAfterResetIssued is the delay used while waiting for a machine
	// to come back in maintenance mode after a reset.
	requeueAfterResetIssued = 10 * time.Second

	// resetRateLimitWindow is the minimum delay between two reset issues
	// against the same machine.
	resetRateLimitWindow = 90 * time.Second

	// clusterNameLabel is the CAPI label carrying the owning cluster name.
	clusterNameLabel = "cluster.x-k8s.io/cluster-name"

	// kubeletServiceID is the Talos service restarted after a bundle-match
	// re-adoption so the workload-cluster Node is re-registered.
	kubeletServiceID = "kubelet"

	// requeueAfterNodeLink is the delay between two attempts to retrigger the
	// owning CAPI Machine's node-link reconciliation after adoption.
	requeueAfterNodeLink = 30 * time.Second

	// nodeLinkRetriggerAnnotation is bumped on an adopted ByotMachine whose
	// owning Machine has not yet linked its workload Node (status.nodeRef).
	// Each bump changes the ByotMachine object, retriggers the CAPI Machine
	// controller (which watches the infra ref), and makes it re-list the
	// workload nodes to match spec.providerID. This compensates for the
	// control-plane bootstrap race where the workload API is down while the
	// Machine controller first reconciles, so its node watch never observes
	// the control-plane Node registering.
	nodeLinkRetriggerAnnotation = "infrastructure.cluster.x-k8s.io/node-link-retrigger"
)

// MachineAdoptedCondition reports whether the machine configuration has been
// applied to the adopted machine.
const MachineAdoptedCondition clusterv1.ConditionType = "MachineAdopted"

// ResetPerformedCondition reports the state of a machine reset requested via
// spec.joinPolicy=Reset or executed during deletion.
const ResetPerformedCondition clusterv1.ConditionType = "ResetPerformed"

// JoinPreflightCondition reports the outcome of the join preflight: whether
// the machine is safe to adopt with spec.joinPolicy=None, i.e. it is in
// maintenance mode or already carries this cluster's PKI bundle.
const JoinPreflightCondition clusterv1.ConditionType = "JoinPreflight"

// KubeletRestartNudgeCondition reports the outcome of the best-effort kubelet
// restart issued after a split-re-adopt (splitPolicy=None) so the workload
// Node re-registers. Its failure is non-fatal: the configuration apply already
// succeeded and the kubelet (re)starts on boot regardless.
const KubeletRestartNudgeCondition clusterv1.ConditionType = "KubeletRestartNudge"

// nodeLinkRetriggerSelfFilter is a watch predicate that drops Update events
// whose only change is the nodeLinkRetriggerAnnotation. The ByotMachine
// reconciler bumps that annotation to retrigger the owning CAPI Machine's
// node-link, then requeues after requeueAfterNodeLink.
type nodeLinkRetriggerSelfFilter struct{}

func (nodeLinkRetriggerSelfFilter) Create(event.CreateEvent) bool   { return true }
func (nodeLinkRetriggerSelfFilter) Delete(event.DeleteEvent) bool   { return true }
func (nodeLinkRetriggerSelfFilter) Generic(event.GenericEvent) bool { return true }

// Update drops the event when the only change between old and new is the
// nodeLinkRetriggerAnnotation value.
func (nodeLinkRetriggerSelfFilter) Update(evt event.UpdateEvent) bool {
	if evt.ObjectOld == nil || evt.ObjectNew == nil {
		return true
	}

	oldAnn := withoutNodeLinkRetrigger(evt.ObjectOld.GetAnnotations())
	newAnn := withoutNodeLinkRetrigger(evt.ObjectNew.GetAnnotations())

	return !maps.Equal(oldAnn, newAnn) ||
		evt.ObjectOld.GetGeneration() != evt.ObjectNew.GetGeneration()
}

// withoutNodeLinkRetrigger returns a copy of annotations with the
// nodeLinkRetriggerAnnotation key removed.
func withoutNodeLinkRetrigger(annotations map[string]string) map[string]string {
	if len(annotations) == 0 {
		return map[string]string{}
	}

	filtered := make(map[string]string, len(annotations))
	for k, v := range annotations {
		if k == nodeLinkRetriggerAnnotation {
			continue
		}

		filtered[k] = v
	}

	return filtered
}

// ByotMachineReconciler reconciles a ByotMachine object.
type ByotMachineReconciler struct {
	Client ctrlclient.Client
	Scheme *runtime.Scheme
}

// NewByotMachineReconciler creates a new ByotMachineReconciler.
func NewByotMachineReconciler(client ctrlclient.Client) *ByotMachineReconciler {
	return &ByotMachineReconciler{
		Client: client,
		Scheme: client.Scheme(),
	}
}

// SetupWithManager sets up the controller with the Manager.
func (r *ByotMachineReconciler) SetupWithManager(
	manager ctrl.Manager,
	options ctrlcontroller.Options,
) error {
	err := ctrl.NewControllerManagedBy(manager).
		For(&infrav1.ByotMachine{}, builder.WithPredicates(nodeLinkRetriggerSelfFilter{})).
		WithOptions(options).
		Complete(r)
	if err != nil {
		return fmt.Errorf("failed to build ByotMachine controller: %w", err)
	}

	return nil
}

