// Reconcile adopts the Talos machine referenced by the ByotMachine.
func (r *ByotMachineReconciler) Reconcile(ctx context.Context, req ctrl.Request) (ctrl.Result, error) {
	byotMachine := &infrav1.ByotMachine{}

	err := r.Client.Get(ctx, req.NamespacedName, byotMachine)
	if err != nil {
		if apierrors.IsNotFound(err) {
			return ctrl.Result{}, nil
		}

		return ctrl.Result{}, fmt.Errorf("failed to get ByotMachine %s: %w", req.NamespacedName, err)
	}

	if !byotMachine.DeletionTimestamp.IsZero() {
		return r.reconcileDelete(ctx, byotMachine)
	}

	_, err = finalizers.EnsureFinalizer(ctx, r.Client, byotMachine, byotMachineFinalizer)
	if err != nil {
		return ctrl.Result{}, fmt.Errorf("failed to add finalizer to ByotMachine %s: %w", req.NamespacedName, err)
	}

	result, err := r.adopt(ctx, byotMachine)
	if err != nil {
		return result, fmt.Errorf("failed to adopt ByotMachine %s: %w", req.NamespacedName, err)
	}

	return result, nil
}

func (r *ByotMachineReconciler) adopt(ctx context.Context, byotMachine *infrav1.ByotMachine) (ctrl.Result, error) {
	patchHelper, err := patch.NewHelper(byotMachine, r.Client)
	if err != nil {
		return ctrl.Result{}, fmt.Errorf("failed to create patch helper: %w", err)
	}

	machine, machineConfig, wait, err := r.adoptionInputs(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, err
	}

	if wait != nil {
		return *wait, nil
	}

	configHash := sha256Hex(machineConfig)

	if configUnchanged(byotMachine, configHash) {
		return ctrl.Result{}, nil
	}

	if byotMachine.Spec.ForceReset && !byotMachine.Status.Ready {
		result, handled, err := r.ensureForceReset(ctx, patchHelper, byotMachine)
		if err != nil {
			return result, err
		}

		if handled {
			return result, nil
		}
	}

	return r.applyAndMarkAdopted(ctx, patchHelper, machine, byotMachine, machineConfig, configHash)
}

// applyAndMarkAdopted resolves authentication, applies the machine
// configuration, and marks the ByotMachine adopted.
func (r *ByotMachineReconciler) applyAndMarkAdopted(
	ctx context.Context,
	patchHelper *patch.Helper,
	machine *clusterv1.Machine,
	byotMachine *infrav1.ByotMachine,
	machineConfig []byte,
	configHash string,
) (ctrl.Result, error) {
	logger := log.FromContext(ctx)

	talosConfig, result, err := r.resolveTalosConfig(ctx, machine, byotMachine)
	if err != nil {
		return ctrl.Result{}, err
	}

	if result != nil {
		return *result, nil
	}

	err = applyMachineConfig(ctx, byotMachine.Spec.PublicIP, machineConfig, talosConfig)
	if err != nil {
		return ctrl.Result{}, r.recordApplyFailure(ctx, patchHelper, byotMachine, err)
	}

	markAdopted(byotMachine, configHash)

	err = patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, fmt.Errorf("failed to patch ByotMachine: %w", err)
	}

	logger.Info("Machine adopted", "byotMachine", byotMachine.Name, "publicIP", byotMachine.Spec.PublicIP)

	return ctrl.Result{}, nil
}

// reconcileDelete resets the machine back to a clean state (wiping the STATE
// and EPHEMERAL volumes) before releasing it. Deletion blocks until the reset
// succeeds, guaranteeing machines leave the cluster wiped.
func (r *ByotMachineReconciler) reconcileDelete(
	ctx context.Context,
	byotMachine *infrav1.ByotMachine,
) (ctrl.Result, error) {
	logger := log.FromContext(ctx)

	if !controllerutil.ContainsFinalizer(byotMachine, byotMachineFinalizer) {
		return ctrl.Result{}, nil
	}

	err := r.resetWithResolvedAuth(ctx, byotMachine)
	if err != nil {
		logger.Info("Reset on delete failed, retrying",
			"byotMachine", byotMachine.Name,
			"publicIP", byotMachine.Spec.PublicIP,
			"error", err.Error())

		return ctrl.Result{RequeueAfter: requeueAfterResetIssued}, nil
	}

	if controllerutil.RemoveFinalizer(byotMachine, byotMachineFinalizer) {
		err = r.Client.Update(ctx, byotMachine)
		if err != nil {
			return ctrl.Result{}, fmt.Errorf("failed to remove finalizer from ByotMachine %s: %w", byotMachine.Name, err)
		}
	}

	logger.Info("Machine reset and released", "byotMachine", byotMachine.Name, "publicIP", byotMachine.Spec.PublicIP)

	return ctrl.Result{}, nil
}

// resetWithResolvedAuth resets the machine using the first working
// credential, in order: spec.talosConfigSecretRef, the cluster's own
// talosconfig, then an insecure client for machines still in maintenance mode.
func (r *ByotMachineReconciler) resetWithResolvedAuth(
	ctx context.Context,
	byotMachine *infrav1.ByotMachine,
) error {
	publicIP := byotMachine.Spec.PublicIP

	candidates, err := r.resetCredentialCandidates(ctx, byotMachine)
	if err != nil {
		return err
	}

	return attemptReset(ctx, candidates, publicIP)
}

// attemptReset tries each credential candidate (a nil candidate selects the
// insecure maintenance client) and returns the last error if all fail.
func attemptReset(ctx context.Context, candidates [][]byte, publicIP string) error {
	var lastErr error

	for _, candidate := range candidates {
		err := resetMachine(ctx, publicIP, candidate)
		if err == nil {
			return nil
		}

		lastErr = err
	}

	if lastErr != nil {
		return fmt.Errorf("failed to reset machine %s with any available credentials: %w", publicIP, lastErr)
	}

	return fmt.Errorf("%w: %s", ErrNoResetCredentials, publicIP)
}

// resetCredentialCandidates returns talosconfig candidates for the reset, in
// priority order, terminated by a nil entry which selects the insecure
// (maintenance) client.
func (r *ByotMachineReconciler) resetCredentialCandidates(
	ctx context.Context,
	byotMachine *infrav1.ByotMachine,
) ([][]byte, error) {
	candidates := [][]byte{}

	if byotMachine.Spec.TalosConfigSecretRef != nil {
		talosConfig, err := r.referencedTalosConfig(ctx, byotMachine.Spec.TalosConfigSecretRef.Name, byotMachine.Namespace)
		if err != nil && !errors.Is(err, ErrClusterTalosConfigNotReady) {
			return nil, fmt.Errorf("failed to load referenced talosconfig: %w", err)
		}

		if err == nil {
			candidates = append(candidates, talosConfig)
		}
	}

	clusterName := byotMachine.Labels[clusterNameLabel]
	if clusterName != "" {
		talosConfig, err := r.clusterTalosConfig(ctx, clusterName, byotMachine.Namespace)
		if err != nil && !errors.Is(err, ErrClusterTalosConfigNotReady) {
			return nil, fmt.Errorf("failed to load cluster talosconfig: %w", err)
		}

		if err == nil {
			candidates = append(candidates, talosConfig)
		}
	}

	return append(candidates, nil), nil
}

// ensureForceReset performs the pre-adoption reset when spec.forceReset is
// set. handled is true when the caller must return the given result instead
// of proceeding to the configuration apply.
func (r *ByotMachineReconciler) ensureForceReset(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
) (ctrl.Result, bool, error) {
	logger := log.FromContext(ctx)

	if probeMaintenance(ctx, byotMachine.Spec.PublicIP) {
		// The machine is in maintenance mode: any previously applied
		// configuration is gone.
		byotMachine.Status.LastAppliedConfigSHA = ""

		conditions.MarkTrue(byotMachine, ResetPerformedCondition)

		err := patchHelper.Patch(ctx, byotMachine)
		if err != nil {
			return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine after reset confirmation: %w", err)
		}

		logger.Info("Reset confirmed, machine in maintenance mode", "byotMachine", byotMachine.Name)

		return ctrl.Result{}, false, nil
	}

	if lastReset := byotMachine.Status.LastResetAt; lastReset != nil && time.Since(lastReset.Time) < resetRateLimitWindow {
		return ctrl.Result{RequeueAfter: requeueAfterResetIssued}, true, nil
	}

	candidates, err := r.resetCredentialCandidates(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, err
	}

	resetErr := attemptReset(ctx, withoutInsecure(candidates), byotMachine.Spec.PublicIP)
	if resetErr != nil {
		return ctrl.Result{}, true, r.recordResetFailure(ctx, patchHelper, byotMachine, resetErr)
	}

	now := metav1.Now()
	byotMachine.Status.LastResetAt = &now

	conditions.MarkFalse(
		byotMachine,
		ResetPerformedCondition,
		"ResetInProgress",
		clusterv1.ConditionSeverityInfo,
		"reset issued, waiting for maintenance mode",
	)

	err = patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine after reset issued: %w", err)
	}

	logger.Info("Reset issued to machine", "byotMachine", byotMachine.Name, "publicIP", byotMachine.Spec.PublicIP)

	return ctrl.Result{RequeueAfter: requeueAfterResetIssued}, true, nil
}

// withoutInsecure drops the trailing nil (insecure maintenance) candidate: a
// configured machine must be reset via authenticated credentials before
// adoption.
func withoutInsecure(candidates [][]byte) [][]byte {
	if len(candidates) > 0 && candidates[len(candidates)-1] == nil {
		return candidates[:len(candidates)-1]
	}

	return candidates
}

// recordResetFailure marks the reset condition false, persists it, and
// returns the reset error as the reconcile failure.
func (r *ByotMachineReconciler) recordResetFailure(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	resetErr error,
) error {
	conditions.MarkFalse(
		byotMachine,
		ResetPerformedCondition,
		"ResetFailed",
		clusterv1.ConditionSeverityWarning,
		"%s",
		resetErr.Error(),
	)

	err := patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return fmt.Errorf("failed to patch ByotMachine after reset failure: %w", err)
	}

	return resetErr
}

// adoptionInputs resolves the owner Machine and its bootstrap data. A non-nil
// wait result means one of them is not available yet; the caller should
// requeue with it.
func (r *ByotMachineReconciler) adoptionInputs(
	ctx context.Context,
	byotMachine *infrav1.ByotMachine,
) (*clusterv1.Machine, []byte, *ctrl.Result, error) {
	logger := log.FromContext(ctx)

	machine, err := util.GetOwnerMachine(ctx, r.Client, byotMachine.ObjectMeta)
	if err != nil {
		return nil, nil, nil, fmt.Errorf("failed to get owner Machine: %w", err)
	}

	if machine == nil {
		logger.Info("Waiting for Machine controller to set OwnerReference", "byotMachine", byotMachine.Name)

		return nil, nil, &ctrl.Result{RequeueAfter: requeueAfterBootstrap}, nil
	}

	machineConfig, err := r.bootstrapData(ctx, machine)
	if errors.Is(err, ErrBootstrapDataNotReady) {
		logger.Info("Waiting for bootstrap data", "byotMachine", byotMachine.Name, "machine", machine.Name)

		return nil, nil, &ctrl.Result{RequeueAfter: requeueAfterBootstrap}, nil
	}

	if err != nil {
		return nil, nil, nil, err
	}

	return machine, machineConfig, nil, nil
}

// recordApplyFailure marks the adoption condition false, persists it, and
// returns the apply error as the reconcile failure.
func (r *ByotMachineReconciler) recordApplyFailure(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	applyErr error,
) error {
	conditions.MarkFalse(
		byotMachine,
		MachineAdoptedCondition,
		"ApplyFailed",
		clusterv1.ConditionSeverityWarning,
		"%s",
		applyErr.Error(),
	)

	err := patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return fmt.Errorf("failed to patch ByotMachine after apply failure: %w", err)
	}

	return applyErr
}

// markAdopted updates the ByotMachine spec and status after a successful
// machine configuration apply.
func markAdopted(byotMachine *infrav1.ByotMachine, configHash string) {
	providerID := infrav1.ProviderIDPrefix + byotMachine.Spec.PublicIP

	byotMachine.Spec.ProviderID = &providerID
	byotMachine.Status.Ready = true
	byotMachine.Status.LastAppliedConfigSHA = configHash
	byotMachine.Status.Addresses = []clusterv1.MachineAddress{
		{
			Type:    clusterv1.MachineExternalIP,
			Address: byotMachine.Spec.PublicIP,
		},
	}

	conditions.MarkTrue(byotMachine, MachineAdoptedCondition)
}

// configUnchanged reports whether the machine is already adopted with the
// same configuration that would be applied now.
func configUnchanged(byotMachine *infrav1.ByotMachine, configHash string) bool {
	return byotMachine.Status.Ready &&
		byotMachine.Spec.ProviderID != nil &&
		byotMachine.Status.LastAppliedConfigSHA == configHash
}

func sha256Hex(data []byte) string {
	sum := sha256.Sum256(data)

	return hex.EncodeToString(sum[:])
}

// bootstrapData reads the Talos machine configuration produced by the
// bootstrap provider for the given Machine.
func (r *ByotMachineReconciler) bootstrapData(
	ctx context.Context,
	machine *clusterv1.Machine,
) ([]byte, error) {
	if machine.Spec.Bootstrap.DataSecretName == nil {
		return nil, ErrBootstrapDataNotReady
	}

	secret := &corev1.Secret{}
	secretKey := ctrlclient.ObjectKey{
		Namespace: machine.Namespace,
		Name:      *machine.Spec.Bootstrap.DataSecretName,
	}

	err := r.Client.Get(ctx, secretKey, secret)
	if err != nil {
		if apierrors.IsNotFound(err) {
			return nil, ErrBootstrapDataNotReady
		}

		return nil, fmt.Errorf("failed to get bootstrap secret %s: %w", secretKey, err)
	}

	data, ok := secret.Data[bootstrapSecretDataKey]
	if !ok || len(data) == 0 {
		return nil, ErrBootstrapDataEmpty
	}

	return data, nil
}

// resolveTalosConfig picks the talosconfig to authenticate with, and returns
// nil for machines still in maintenance mode. A non-nil result signals the
// reconcile should requeue while the needed secret becomes available.
func (r *ByotMachineReconciler) resolveTalosConfig(
	ctx context.Context,
	machine *clusterv1.Machine,
	byotMachine *infrav1.ByotMachine,
) ([]byte, *ctrl.Result, error) {
	logger := log.FromContext(ctx)

	// A force-reset machine confirmed in maintenance mode has no PKI: apply
	// with the insecure client, ignoring spec.talosConfigSecretRef.
	if byotMachine.Spec.ForceReset &&
		!byotMachine.Status.Ready &&
		conditions.IsTrue(byotMachine, ResetPerformedCondition) {
		return nil, nil, nil
	}

	// Re-application on an already-configured machine: use the cluster's own
	// talosconfig (the machine carries our PKI since its first apply).
	if byotMachine.Status.Ready {
		talosConfig, err := r.clusterTalosConfig(ctx, machine.Spec.ClusterName, byotMachine.Namespace)
		if errors.Is(err, ErrClusterTalosConfigNotReady) {
			logger.Info("Waiting for cluster talosconfig", "byotMachine", byotMachine.Name)

			return nil, &ctrl.Result{RequeueAfter: requeueAfterBootstrap}, nil
		}

		return talosConfig, nil, err
	}

	// Foreign machine takeover: use the talosconfig of its CURRENT setup.
	if byotMachine.Spec.TalosConfigSecretRef != nil {
		talosConfig, err := r.referencedTalosConfig(ctx, byotMachine.Spec.TalosConfigSecretRef.Name, byotMachine.Namespace)
		if errors.Is(err, ErrClusterTalosConfigNotReady) {
			logger.Info("Waiting for referenced talosconfig secret", "byotMachine", byotMachine.Name)

			return nil, &ctrl.Result{RequeueAfter: requeueAfterBootstrap}, nil
		}

		return talosConfig, nil, err
	}

	return nil, nil, nil
}

// clusterTalosConfig loads the talosconfig generated by the bootstrap provider
// for the given cluster (secret "<cluster>-talosconfig").
func (r *ByotMachineReconciler) clusterTalosConfig(
	ctx context.Context,
	clusterName string,
	namespace string,
) ([]byte, error) {
	return r.referencedTalosConfig(ctx, clusterName+clusterTalosConfigSecretSuffix, namespace)
}

// referencedTalosConfig loads a talosconfig document from a secret in the
// same namespace. A missing secret is treated as a not-ready state.
func (r *ByotMachineReconciler) referencedTalosConfig(
	ctx context.Context,
	secretName string,
	namespace string,
) ([]byte, error) {
	secret := &corev1.Secret{}
	secretKey := ctrlclient.ObjectKey{
		Namespace: namespace,
		Name:      secretName,
	}

	err := r.Client.Get(ctx, secretKey, secret)
	if err != nil {
		if apierrors.IsNotFound(err) {
			return nil, ErrClusterTalosConfigNotReady
		}

		return nil, fmt.Errorf("failed to get talosconfig secret %s: %w", secretKey, err)
	}

	data, ok := secret.Data[talosConfigSecretDataKey]
	if !ok || len(data) == 0 {
		return nil, ErrClusterTalosConfigNotReady
	}

	return data, nil
}
