// markAdopted updates the ByotMachine spec and status after a successful
// machine configuration apply.
func markAdopted(byotMachine *infrav1.ByotMachine, configHash string) {
	providerID := infrav1.ProviderIDPrefix + byotMachine.Spec.PublicIP

	byotMachine.Spec.ProviderID = &providerID
	byotMachine.Status.Ready = true
	byotMachine.Status.LastAppliedConfigSHA = configHash
	byotMachine.Status.Addresses = []clusterv1.MachineAddress{
		{
			Type:    clusterv1.MachineExternalIP,
			Address: byotMachine.Spec.PublicIP,
		},
	}

	conditions.MarkTrue(byotMachine, MachineAdoptedCondition)
}

// configUnchanged reports whether the machine is already adopted with the
// same configuration that would be applied now.
func configUnchanged(byotMachine *infrav1.ByotMachine, configHash string) bool {
	return byotMachine.Status.Ready &&
		byotMachine.Spec.ProviderID != nil &&
		byotMachine.Status.LastAppliedConfigSHA == configHash
}

func sha256Hex(data []byte) string {
	sum := sha256.Sum256(data)

	return hex.EncodeToString(sum[:])
}

// bootstrapData reads the Talos machine configuration produced by the
// bootstrap provider for the given Machine.
func (r *ByotMachineReconciler) bootstrapData(
	ctx context.Context,
	machine *clusterv1.Machine,
) ([]byte, error) {
	if machine.Spec.Bootstrap.DataSecretName == nil {
		return nil, ErrBootstrapDataNotReady
	}

	secret := &corev1.Secret{}
	secretKey := ctrlclient.ObjectKey{
		Namespace: machine.Namespace,
		Name:      *machine.Spec.Bootstrap.DataSecretName,
	}

	err := r.Client.Get(ctx, secretKey, secret)
	if err != nil {
		if apierrors.IsNotFound(err) {
			return nil, ErrBootstrapDataNotReady
		}

		return nil, fmt.Errorf("failed to get bootstrap secret %s: %w", secretKey, err)
	}

	data, ok := secret.Data[bootstrapSecretDataKey]
	if !ok || len(data) == 0 {
		return nil, ErrBootstrapDataEmpty
	}

	return data, nil
}

// preflightForeignMachine handles a machine that is neither in maintenance
// mode nor accepting the cluster's own talosconfig. When the machine provably
// answers with a referenced foreign talosconfig, the join preflight fails
// with a bundle mismatch; otherwise the referenced config (if any) is used
// for the apply attempt, preserving the previous behavior for unreachable
// machines.
func (r *ByotMachineReconciler) preflightForeignMachine(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
) ([]byte, *ctrl.Result, error) {
	logger := log.FromContext(ctx)

	if byotMachine.Spec.TalosConfigSecretRef == nil {
		// Configured machine without credentials: treat it as a bundle
		// mismatch, it cannot be joined without resetting it first.
		return nil, nil, r.recordPreflightFailure(ctx, patchHelper, byotMachine, "NoCredentials", ErrJoinNoCredentials)
	}

	talosConfig, err := r.referencedTalosConfig(ctx, byotMachine.Spec.TalosConfigSecretRef.Name, byotMachine.Namespace)
	if errors.Is(err, ErrClusterTalosConfigNotReady) {
		logger.Info("Waiting for referenced talosconfig secret", "byotMachine", byotMachine.Name)

		return nil, &ctrl.Result{RequeueAfter: requeueAfterBootstrap}, nil
	}

	if err != nil {
		return nil, nil, err
	}

	if probeAuthenticated(ctx, byotMachine.Spec.PublicIP, talosConfig) {
		return nil, nil, r.recordPreflightFailure(ctx, patchHelper, byotMachine, "BundleMismatch", ErrJoinBundleMismatch)
	}

	return talosConfig, nil, nil
}

// recordPreflightFailure marks the join preflight condition false, persists
// it, and returns the preflight error as the reconcile failure.
func (r *ByotMachineReconciler) recordPreflightFailure(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	reason string,
	preflightErr error,
) error {
	conditions.MarkFalse(
		byotMachine,
		JoinPreflightCondition,
		reason,
		clusterv1.ConditionSeverityError,
		"%s",
		preflightErr.Error(),
	)

	err := patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return fmt.Errorf("failed to patch ByotMachine after join preflight failure: %w", err)
	}

	return preflightErr
}

// clusterTalosConfig loads the talosconfig generated by the bootstrap provider
// for the given cluster (secret "<cluster>-talosconfig").
func (r *ByotMachineReconciler) clusterTalosConfig(
	ctx context.Context,
	clusterName string,
	namespace string,
) ([]byte, error) {
	return r.referencedTalosConfig(ctx, clusterName+clusterTalosConfigSecretSuffix, namespace)
}

// referencedTalosConfig loads a talosconfig document from a secret in the
// same namespace. A missing secret is treated as a not-ready state.
func (r *ByotMachineReconciler) referencedTalosConfig(
	ctx context.Context,
	secretName string,
	namespace string,
) ([]byte, error) {
	secret := &corev1.Secret{}
	secretKey := ctrlclient.ObjectKey{
		Namespace: namespace,
		Name:      secretName,
	}

	err := r.Client.Get(ctx, secretKey, secret)
	if err != nil {
		if apierrors.IsNotFound(err) {
			return nil, ErrClusterTalosConfigNotReady
		}

		return nil, fmt.Errorf("failed to get talosconfig secret %s: %w", secretKey, err)
	}

	data, ok := secret.Data[talosConfigSecretDataKey]
	if !ok || len(data) == 0 {
		return nil, ErrClusterTalosConfigNotReady
	}

	return data, nil
}
