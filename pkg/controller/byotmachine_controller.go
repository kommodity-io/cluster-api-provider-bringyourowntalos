// Reconcile adopts the Talos machine referenced by the ByotMachine.
func (r *ByotMachineReconciler) Reconcile(ctx context.Context, req ctrl.Request) (ctrl.Result, error) {
	byotMachine := &infrav1.ByotMachine{}

	err := r.Client.Get(ctx, req.NamespacedName, byotMachine)
	if err != nil {
		if apierrors.IsNotFound(err) {
			return ctrl.Result{}, nil
		}

		return ctrl.Result{}, fmt.Errorf("failed to get ByotMachine %s: %w", req.NamespacedName, err)
	}

	if !byotMachine.DeletionTimestamp.IsZero() {
		return r.reconcileDelete(ctx, byotMachine)
	}

	_, err = finalizers.EnsureFinalizer(ctx, r.Client, byotMachine, byotMachineFinalizer)
	if err != nil {
		return ctrl.Result{}, fmt.Errorf("failed to add finalizer to ByotMachine %s: %w", req.NamespacedName, err)
	}

	result, err := r.adopt(ctx, byotMachine)
	if err != nil {
		return result, fmt.Errorf("failed to adopt ByotMachine %s: %w", req.NamespacedName, err)
	}

	return result, nil
}

func (r *ByotMachineReconciler) adopt(ctx context.Context, byotMachine *infrav1.ByotMachine) (ctrl.Result, error) {
	patchHelper, err := patch.NewHelper(byotMachine, r.Client)
	if err != nil {
		return ctrl.Result{}, fmt.Errorf("failed to create patch helper: %w", err)
	}

	machine, machineConfig, wait, err := r.adoptionInputs(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, err
	}

	if wait != nil {
		return *wait, nil
	}

	// Claim a ByotHost before adopting. The host's public IP is the adoption
	// target; claiming is idempotent once resolvedHost is set.
	claimResult, handled, err := r.claimHost(ctx, byotMachine, patchHelper)
	if err != nil {
		return ctrl.Result{}, err
	}

	if handled {
		return claimResult, nil
	}

	configHash := sha256Hex(machineConfig)

	// A Failed upgrade is terminal until the operator retriggers (generation
	// bump clears it via retriggerStaleUpgradeFailure). finalizeUpgradeFailure
	// reset the host to maintenance and cleared LastAppliedConfigSHA, so
	// configUnchanged is false — but re-applying the config here would re-adopt
	// and re-join the node the reset just evicted. Skip the apply and let
	// reconcileAdopted stop on the Failed state.
	if byotMachine.Status.UpgradeState == infrav1.UpgradeStateFailed {
		return r.reconcileAdopted(ctx, patchHelper, byotMachine, machine)
	}

	if configUnchanged(byotMachine, configHash) {
		return r.reconcileAdopted(ctx, patchHelper, byotMachine, machine)
	}

	return r.applyAndMarkAdopted(ctx, patchHelper, machine, byotMachine, machineConfig, configHash)
}

// reconcileAdopted drives the steady-state path for an already-adopted
// ByotMachine: run the post-adoption Talos upgrade (opt-in via
// DesiredTalosVersion) BEFORE linking the workload Node. The upgrade runs
// over the cluster talosconfig (Admin) once the host carries the cluster PKI
// bundle, since a maintenance client cannot call Upgrade (Talos authz).
//
// Upgrade-before-link is the non-disruptive rollout order: a freshly-claimed
// host reboots onto the desired Talos version while it is still unlinked
// (no workload, and CAPI's MachineDeployment has not yet removed the old
// node — it waits for the new Machine's nodeRef). Only once the host is on
// the desired version (or version management is opted out) does linkNode
// make the node live and let the MachineDeployment roll the old node away.
// Returns handled=true while the upgrade is in flight (InFlight) or stopped
// on failure, so the caller returns its result instead of linking.
func (r *ByotMachineReconciler) reconcileAdopted(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	machine *clusterv1.Machine,
) (ctrl.Result, error) {
	upgradeResult, handled, err := r.ensureTalosVersion(ctx, patchHelper, byotMachine, machine)
	if err != nil {
		return upgradeResult, err
	}

	if handled {
		return upgradeResult, nil
	}

	return r.linkNode(ctx, patchHelper, byotMachine, machine)
}

// resolveApplyAuth picks the talosconfig to authenticate the configuration
// apply with, and returns nil for machines in maintenance mode. A non-nil
// result signals the reconcile should requeue while a needed secret becomes
// available. bundleMatch is true when the machine already carries this
// cluster's PKI bundle.
//
// For machines not yet adopted, it first runs the join preflight, which
// determines whether the machine is maintenance-mode, carries this cluster's
// PKI bundle, or carries a foreign bundle (in which case adoption fails).
func (r *ByotMachineReconciler) resolveApplyAuth(
	ctx context.Context,
	patchHelper *patch.Helper,
	machine *clusterv1.Machine,
	byotMachine *infrav1.ByotMachine,
) ([]byte, bool, *ctrl.Result, error) {
	// Re-application on an already-adopted machine: use the cluster's own
	// talosconfig (the machine carries our PKI since its first apply).
	if byotMachine.Status.Ready {
		talosConfig, result, err := r.awaitClusterTalosConfig(ctx, machine.Spec.ClusterName, byotMachine)

		return talosConfig, true, result, err
	}

	return r.preflightJoin(ctx, patchHelper, machine, byotMachine)
}

// awaitClusterTalosConfig loads the cluster's own talosconfig, requeueing
// while the bootstrap provider has not generated it yet.
func (r *ByotMachineReconciler) awaitClusterTalosConfig(
	ctx context.Context,
	clusterName string,
	byotMachine *infrav1.ByotMachine,
) ([]byte, *ctrl.Result, error) {
	logger := log.FromContext(ctx)

	talosConfig, err := r.clusterTalosConfig(ctx, clusterName, byotMachine.Namespace)
	if errors.Is(err, ErrClusterTalosConfigNotReady) {
		logger.Info("Waiting for cluster talosconfig", "byotMachine", byotMachine.Name)

		return nil, &ctrl.Result{RequeueAfter: requeueAfterBootstrap}, nil
	}

	return talosConfig, nil, err
}

// preflightJoin determines whether a machine being adopted for the first time
// is in maintenance mode or carries this cluster's PKI bundle, and returns the
// matching authentication. A machine that answers the Talos API with a foreign
// bundle fails the preflight instead of being silently misconfigured (see
// PLA-6479).
func (r *ByotMachineReconciler) preflightJoin(
	ctx context.Context,
	patchHelper *patch.Helper,
	machine *clusterv1.Machine,
	byotMachine *infrav1.ByotMachine,
) ([]byte, bool, *ctrl.Result, error) {
	publicIP := byotMachine.Status.ResolvedPublicIP

	if r.probeMaintenance(ctx, publicIP) {
		conditions.Set(byotMachine, &clusterv1.Condition{
			Type:   JoinPreflightCondition,
			Status: corev1.ConditionTrue,
			Reason: "MaintenanceMode",
		})

		return nil, false, nil, nil
	}

	talosConfig, err := r.clusterTalosConfig(ctx, machine.Spec.ClusterName, byotMachine.Namespace)
	if errors.Is(err, ErrClusterTalosConfigNotReady) {
		logger := log.FromContext(ctx)
		logger.Info("Waiting for cluster talosconfig", "byotMachine", byotMachine.Name)

		return nil, false, &ctrl.Result{RequeueAfter: requeueAfterBootstrap}, nil
	}

	if err != nil {
		return nil, false, nil, err
	}

	if r.probeAuthenticated(ctx, publicIP, talosConfig) {
		conditions.Set(byotMachine, &clusterv1.Condition{
			Type:   JoinPreflightCondition,
			Status: corev1.ConditionTrue,
			Reason: "BundleMatch",
		})

		return talosConfig, true, nil, nil
	}

	talosConfig, result, err := r.preflightForeignMachine(ctx, patchHelper, byotMachine)

	return talosConfig, false, result, err
}

// ensureTalosVersion drives the post-adoption Talos upgrade state machine.
// It is opt-in (only runs when DesiredTalosVersion is set) and runs after the
// machine is adopted (Ready=true): the upgrade uses the cluster talosconfig
// (mTLS, Admin) because a maintenance-mode client is Reader-only and cannot
// call Upgrade (Talos authz). Returns handled=true while the upgrade is in
// flight (InFlight) or stopped on failure, so the caller returns its result
// instead of ending the reconcile. When opt-out or complete, returns
// handled=false so the reconcile ends cleanly.
//
// The upgrade uses the LifecycleClient.Upgrade RPC (pull + drain + reboot,
// synchronous in one reconcile). The machine config is carried implicitly
// across the reboot (no preserve flag in the lifecycle API); the node
// rejoins the cluster on the new version without re-adoption. Completion is
// gated on a boot-id change (the host rebooted), not a version-match, so
// custom installer tags (e.g. factory.talos.dev/installer/<schematic>:vX.Y or
// a Corti-custom installer with extensions) work — Talos does not enforce a
// tag convention on the upgrade source. Dedup is ref+gen based: a same-ref
// re-issue with a matching attempt generation is skipped (already applied);
// an operator forces a same-ref reinstall by bumping generation.
func (r *ByotMachineReconciler) ensureTalosVersion(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	machine *clusterv1.Machine,
) (ctrl.Result, bool, error) {
	if byotMachine.Spec.DesiredTalosVersion == nil || *byotMachine.Spec.DesiredTalosVersion == "" {
		return ctrl.Result{}, false, nil
	}

	// Post-adoption only: the upgrade needs the cluster talosconfig, which is
	// only usable once the bootstrap config is applied and the host carries
	// the cluster PKI bundle.
	if !byotMachine.Status.Ready {
		return ctrl.Result{}, false, nil
	}

	desired := *byotMachine.Spec.DesiredTalosVersion

	// Retrigger after a stopped failure: an operator edit bumps generation,
	// so a Failed state whose attempt generation is stale is cleared and the
	// state machine restarts from the top.
	_, err := r.retriggerStaleUpgradeFailure(ctx, patchHelper, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, err
	}

	switch byotMachine.Status.UpgradeState {
	case "":
		if desired == "" {
			return r.markInvalidImageRef(ctx, patchHelper, byotMachine)
		}

		if upgradeAlreadyApplied(byotMachine, desired) {
			return r.markUpgradeComplete(ctx, patchHelper, byotMachine)
		}

		return r.upgradeProbeAndIssue(ctx, patchHelper, byotMachine, machine, desired)
	case infrav1.UpgradeStateInFlight:
		return r.upgradeInFlight(ctx, patchHelper, byotMachine, machine)
	case infrav1.UpgradeStateFailed:
		return ctrl.Result{}, true, nil // current-generation failure: stopped
	}

	return ctrl.Result{}, true, nil
}

// upgradeAlreadyApplied reports whether the desired installer ref was already
// applied for the current generation (no-op re-issue). Dedup is ref+gen based:
// an operator forces a same-ref reinstall by bumping generation (retrigger
// above clears Failed); a ref change re-issues. This avoids mass same-version
// reinstalls on a green cluster whose hosts are pre-imaged at
// DesiredTalosVersion. The version-match short-circuit is gone (custom
// installer tags break it; the completion gate is a boot-id change).
func upgradeAlreadyApplied(byotMachine *infrav1.ByotMachine, desired string) bool {
	return byotMachine.Status.UpgradeAppliedImageRef == desired &&
		byotMachine.Status.UpgradeAttemptGeneration == byotMachine.Generation
}

// retriggerStaleUpgradeFailure clears a Failed upgrade state when the
// operator has edited DesiredTalosVersion since the attempt (generation
// bumped), so the state machine restarts. Returns retriggered=true when it
// cleared the state.
func (r *ByotMachineReconciler) retriggerStaleUpgradeFailure(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
) (bool, error) {
	if byotMachine.Status.UpgradeState != infrav1.UpgradeStateFailed ||
		byotMachine.Generation == byotMachine.Status.UpgradeAttemptGeneration {
		return false, nil
	}

	log.FromContext(ctx).Info("Retriggering Talos upgrade after failure", "byotMachine", byotMachine.Name)

	byotMachine.Status.UpgradeState = ""
	byotMachine.Status.UpgradeProbeFailures = 0

	err := patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return false, fmt.Errorf("failed to patch ByotMachine on upgrade retrigger: %w", err)
	}

	return true, nil
}

// markInvalidImageRef records that DesiredTalosVersion is empty/unparseable
// and stops the upgrade (no requeue). With the lifecycle Upgrade migration
// the installer image tag is opaque to Talos, so the only validation is
// "non-empty ref"; tag-shape checks are no longer applied.
func (r *ByotMachineReconciler) markInvalidImageRef(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
) (ctrl.Result, bool, error) {
	conditions.MarkFalse(byotMachine, TalosVersionReadyCondition, "InvalidImageRef",
		clusterv1.ConditionSeverityError, "DesiredTalosVersion is empty")

	byotMachine.Status.UpgradeAttemptGeneration = byotMachine.Generation

	err := patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine on invalid image ref: %w", err)
	}

	return ctrl.Result{}, true, nil
}

// recordUpgradeProbeFailure records a consecutive upgrade probe failure.
// When the threshold is reached it finalizes the upgrade as Failed: it marks
// the condition and, when resetOnFailure is true, resets the host to remove
// the node from the cluster (the upgrade was attempted, so the host is
// reachable and resettable). Version-probe failures (pre-issue, host possibly
// unreachable) pass resetOnFailure=false so the node is left in place for
// recovery. Below the threshold it patches the incremented counter and
// returns a requeue.
func (r *ByotMachineReconciler) recordUpgradeProbeFailure(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	threshold int32,
	reason string,
	probeErr error,
	resetOnFailure bool,
) (ctrl.Result, bool, error) {
	byotMachine.Status.UpgradeProbeFailures++

	// Persist the counter via the caller's helper, whose base predates the
	// increment (so the diff is real). finalizeUpgradeFailure takes a fresh
	// helper that would no-op the counter (its base already includes it).
	err := patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine on upgrade probe retry: %w", err)
	}

	if byotMachine.Status.UpgradeProbeFailures >= threshold {
		if resetOnFailure {
			return r.finalizeUpgradeFailure(ctx, patchHelper, byotMachine, reason, probeErr)
		}

		byotMachine.Status.UpgradeState = infrav1.UpgradeStateFailed
		byotMachine.Status.UpgradeAttemptGeneration = byotMachine.Generation

		conditions.MarkFalse(byotMachine, TalosVersionReadyCondition, reason,
			clusterv1.ConditionSeverityWarning, "probe failed %d times: %s",
			byotMachine.Status.UpgradeProbeFailures, probeErr.Error())

		err = patchHelper.Patch(ctx, byotMachine, ownedTalosVersionReady())
		if err != nil {
			return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine on upgrade failure: %w", err)
		}

		log.FromContext(ctx).Info("Talos upgrade probe exhausted retries",
			"byotMachine", byotMachine.Name, "publicIP", byotMachine.Status.ResolvedPublicIP)

		return ctrl.Result{}, true, nil
	}

	return ctrl.Result{RequeueAfter: requeueAfterUpgrade}, true, nil
}

// upgradeProbeAndIssue runs the pre-upgrade Version probe over the cluster
// talosconfig. On success it records CurrentTalosVersion (for status display
// and the InFlight reachability fallback) and issues the lifecycle Upgrade
// (pull + drain + reboot, synchronous), stashing the pre-reboot boot-id on
// status for the InFlight completion gate. The version-match short-circuit is
// gone (custom installer tags break it); dedup is gen+ref based at the
// ensureTalosVersion entry. Probe failures accumulate up to
// versionProbeThreshold before the controller stops with VersionProbeFailed.
func (r *ByotMachineReconciler) upgradeProbeAndIssue(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	machine *clusterv1.Machine,
	desired string,
) (ctrl.Result, bool, error) {
	publicIP := byotMachine.Status.ResolvedPublicIP

	talosConfig, result, err := r.awaitClusterTalosConfig(ctx, machine.Spec.ClusterName, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, err
	}

	if result != nil {
		return *result, true, nil
	}

	tag, err := r.versionProbeAuthenticated(ctx, publicIP, talosConfig)
	if err != nil {
		return r.recordUpgradeProbeFailure(ctx, patchHelper, byotMachine,
			versionProbeThreshold, "VersionProbeFailed", err, false)
	}

	byotMachine.Status.CurrentTalosVersion = tag
	byotMachine.Status.UpgradeProbeFailures = 0

	// Set InFlight before issuing the upgrade so a crash between the patch
	// and the call is recoverable (the InFlight poll path re-probes and
	// either completes or, still pre-reboot, requeues). If the upgrade call
	// itself fails, finalize as Failed and reset the host (see
	// finalizeUpgradeFailure) so the node does not linger in the cluster on
	// the wrong Talos version.
	byotMachine.Status.UpgradeState = infrav1.UpgradeStateInFlight
	byotMachine.Status.UpgradeAttemptGeneration = byotMachine.Generation
	byotMachine.Status.UpgradePreRebootBootID = ""

	conditions.MarkFalse(byotMachine, TalosVersionReadyCondition, "Upgrading",
		clusterv1.ConditionSeverityInfo, "upgrading host to %s", desired)

	err = patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine before upgrade: %w", err)
	}

	bootID, err := r.upgradeMachine(ctx, publicIP, talosConfig, desired)
	if err != nil {
		return r.finalizeUpgradeFailure(ctx, patchHelper, byotMachine, "UpgradeFailed", err)
	}

	// Stash the pre-reboot boot-id for the InFlight completion gate. Empty
	// when capture failed or was permission-denied; InFlight then falls back
	// to a reachability + version-change check.
	byotMachine.Status.UpgradePreRebootBootID = bootID

	err = patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine after upgrade: %w", err)
	}

	log.FromContext(ctx).Info("Talos upgrade issued",
		"byotMachine", byotMachine.Name, "publicIP", publicIP, "desired", desired)

	return ctrl.Result{RequeueAfter: requeueAfterUpgrade}, true, nil
}

// finalizeUpgradeFailure marks the upgrade Failed and removes the node from
// the cluster. The node joined when the bootstrap config was applied (before
// the upgrade), so a failed upgrade would otherwise leave it lingering on the
// wrong Talos version. Resetting the host wipes STATE+EPHEMERAL and reboots to
// maintenance, evicting the node; the ByotHost stays claimed (not released) so
// an operator retrigger (generation bump) re-applies the config and re-issues
// the upgrade. Clearing LastAppliedConfigSHA forces that re-apply, and
// Ready=false routes resolveApplyAuth back through maintenance preflight.
func (r *ByotMachineReconciler) finalizeUpgradeFailure(
	ctx context.Context,
	_ *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	reason string,
	upgradeErr error,
) (ctrl.Result, bool, error) {
	// Snapshot the current (issue-time) state as the patch base BEFORE
	// mutating, so the diff to Failed is real. Creating the helper after the
	// mutation would no-op (base == current).
	failedHelper, err := patch.NewHelper(byotMachine, r.Client)
	if err != nil {
		return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine on upgrade failure: %w", err)
	}

	byotMachine.Status.UpgradeState = infrav1.UpgradeStateFailed
	byotMachine.Status.UpgradeAttemptGeneration = byotMachine.Generation

	conditions.MarkFalse(byotMachine, TalosVersionReadyCondition, reason,
		clusterv1.ConditionSeverityWarning, "upgrade failed: %s", upgradeErr.Error())

	err = failedHelper.Patch(ctx, byotMachine, ownedTalosVersionReady())
	if err != nil {
		return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine on upgrade failure: %w", err)
	}

	resetErr := r.resetAdoptedHost(ctx, byotMachine)
	if resetErr != nil {
		log.FromContext(ctx).Info("upgrade-failure host reset failed; retrying",
			"byotMachine", byotMachine.Name, "error", resetErr.Error())

		return ctrl.Result{RequeueAfter: requeueAfterResetIssued}, true, nil
	}

	clearHelper, err := patch.NewHelper(byotMachine, r.Client)
	if err != nil {
		return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine after reset: %w", err)
	}

	byotMachine.Status.Ready = false
	byotMachine.Status.LastAppliedConfigSHA = ""

	err = clearHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine after reset: %w", err)
	}

	log.FromContext(ctx).Info("Talos upgrade failed; host reset to maintenance",
		"byotMachine", byotMachine.Name, "publicIP", byotMachine.Status.ResolvedPublicIP, "reason", reason)

	return ctrl.Result{}, true, nil
}

// resetAdoptedHostImpl wipes an adopted host's STATE+EPHEMERAL volumes and
// reboots it to maintenance mode, using the cluster talosconfig (the host
// carries the PKI bundle from its applied config). The ByotHost is not
// released.
func (r *ByotMachineReconciler) resetAdoptedHostImpl(ctx context.Context, byotMachine *infrav1.ByotMachine) error {
	candidates, err := r.resetCredentialCandidates(ctx, byotMachine)
	if err != nil {
		return err
	}

	return attemptReset(ctx, candidates, byotMachine.Status.ResolvedPublicIP)
}

// upgradeInFlight polls for upgrade completion: the host rebooted into the
// new version. The primary completion gate is a boot-id change (the
// pre-reboot boot-id stashed at issue time differs from the live one). When
// the boot-id is empty (capture failed / permission denied) or the live read
// is permission-denied, it falls back to a reachability + version-change
// check: the Version RPC is reachable AND the live tag differs from the
// pre-upgrade CurrentTalosVersion. Probe failures accumulate up to
// upgradeThreshold before the controller stops with UpgradeFailed.
func (r *ByotMachineReconciler) upgradeInFlight(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	machine *clusterv1.Machine,
) (ctrl.Result, bool, error) {
	publicIP := byotMachine.Status.ResolvedPublicIP

	talosConfig, result, err := r.awaitClusterTalosConfig(ctx, machine.Spec.ClusterName, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, err
	}

	if result != nil {
		return *result, true, nil
	}

	preRebootBootID := byotMachine.Status.UpgradePreRebootBootID
	if preRebootBootID != "" {
		return r.upgradeInFlightBootIDGate(ctx, patchHelper, byotMachine, publicIP, talosConfig, preRebootBootID)
	}

	// Empty pre-reboot boot-id (capture failed / permission denied at issue
	// time): use the reachability + version-change fallback.
	return r.upgradeInFlightVersionFallback(ctx, patchHelper, byotMachine, publicIP, talosConfig)
}

// upgradeInFlightBootIDGate drives the InFlight poll when a pre-reboot boot-id
// was captured. Completes when the live boot-id differs (reboot observed). On
// a permission-denied live read it degrades to the version-change fallback.
func (r *ByotMachineReconciler) upgradeInFlightBootIDGate(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	publicIP string,
	talosConfig []byte,
	preRebootBootID string,
) (ctrl.Result, bool, error) {
	liveBootID, bootErr := r.bootIDAuthenticated(ctx, publicIP, talosConfig)
	if bootErr != nil && !errors.Is(bootErr, errBootIDUnauthorized) {
		return r.recordUpgradeProbeFailure(ctx, patchHelper, byotMachine, upgradeThreshold, "UpgradeFailed", bootErr, true)
	}

	// Permission-denied on the live read: degrade to the version-change
	// fallback (same as an empty pre-reboot boot-id).
	if errors.Is(bootErr, errBootIDUnauthorized) {
		return r.upgradeInFlightVersionFallback(ctx, patchHelper, byotMachine, publicIP, talosConfig)
	}

	if liveBootID != "" && liveBootID != preRebootBootID {
		// Boot-id changed: the host rebooted into the new installer. Refresh
		// CurrentTalosVersion so status reflects the post-upgrade tag — the
		// version-fallback path does this inline, but the boot-id gate would
		// otherwise complete leaving CurrentTalosVersion at the pre-upgrade
		// tag. Best-effort: a probe failure does not block completion (install
		// already succeeded); CurrentTalosVersion stays at its last value.
		tag, err := r.versionProbeAuthenticated(ctx, publicIP, talosConfig)
		if err == nil && tag != "" {
			byotMachine.Status.CurrentTalosVersion = tag
		}

		return r.markUpgradeComplete(ctx, patchHelper, byotMachine)
	}

	err := patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine on upgrade poll: %w", err)
	}

	return ctrl.Result{RequeueAfter: requeueAfterUpgrade}, true, nil
}

// upgradeInFlightVersionFallback drives the InFlight poll when no boot-id is
// available (empty pre-reboot boot-id or permission-denied live read).
// Completes when the Version RPC is reachable AND the live tag differs from
// the pre-upgrade CurrentTalosVersion (recorded at issue time). A reachable
// probe with the same tag keeps InFlight and requeues (reboot not observed).
func (r *ByotMachineReconciler) upgradeInFlightVersionFallback(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	publicIP string,
	talosConfig []byte,
) (ctrl.Result, bool, error) {
	preUpgradeTag := byotMachine.Status.CurrentTalosVersion

	tag, probeErr := r.versionProbeAuthenticated(ctx, publicIP, talosConfig)
	if probeErr != nil {
		return r.recordUpgradeProbeFailure(ctx, patchHelper, byotMachine, upgradeThreshold, "UpgradeFailed", probeErr, true)
	}

	byotMachine.Status.CurrentTalosVersion = tag
	byotMachine.Status.UpgradeProbeFailures = 0

	if tag == "" || tag == preUpgradeTag {
		err := patchHelper.Patch(ctx, byotMachine)
		if err != nil {
			return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine on upgrade poll: %w", err)
		}

		return ctrl.Result{RequeueAfter: requeueAfterUpgrade}, true, nil
	}

	return r.markUpgradeComplete(ctx, patchHelper, byotMachine)
}

// markUpgradeComplete clears the upgrade state and marks TalosVersionReady
// True/Upgraded so the reconcile ends cleanly (the node is adopted and on the
// desired version).
func (r *ByotMachineReconciler) markUpgradeComplete(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
) (ctrl.Result, bool, error) {
	byotMachine.Status.UpgradeState = ""
	byotMachine.Status.UpgradePreRebootBootID = ""

	// Record the applied ref so a subsequent same-ref+same-gen reconcile
	// dedups (no-op re-issue). Set from the spec's DesiredTalosVersion. Also
	// stamp the current generation: spec edits (e.g. providerID linkage,
	// adoption status) bump generation after the upgrade was issued, so the
	// attempt generation recorded at issue time can lag. Without this the
	// ref+gen dedup in upgradeAlreadyApplied would see a stale attempt gen
	// and re-issue the (already-applied) upgrade every reconcile.
	if byotMachine.Spec.DesiredTalosVersion != nil {
		byotMachine.Status.UpgradeAppliedImageRef = *byotMachine.Spec.DesiredTalosVersion
	}

	byotMachine.Status.UpgradeAttemptGeneration = byotMachine.Generation

	conditions.Set(byotMachine, &clusterv1.Condition{
		Type: TalosVersionReadyCondition, Status: corev1.ConditionTrue, Reason: "Upgraded",
	})

	err := patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, fmt.Errorf("failed to patch ByotMachine on upgrade complete: %w", err)
	}

	log.FromContext(ctx).Info("Talos upgrade complete",
		"byotMachine", byotMachine.Name, "publicIP", byotMachine.Status.ResolvedPublicIP,
		"version", byotMachine.Status.CurrentTalosVersion)

	// Mirror the new live version onto the owning ByotHost. The ByotHost
	// controller only (re)discovers the version while the host is in
	// maintenance (Available/Releasing); while Claimed probing is paused, so
	// without this the ByotHost's recorded version goes stale across an
	// in-place upgrade. A failure requeues (idempotent re-run).
	err = r.syncHostTalosVersion(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, true, err
	}

	return ctrl.Result{}, false, nil
}

// syncHostTalosVersion mirrors the ByotMachine's live Talos version
// (status.currentTalosVersion) onto the owning ByotHost's
// status.talosVersion. The ByotHost controller only (re)discovers the version
// while the host is in maintenance (Available/Releasing); while the host is
// Claimed probing is paused, so without this mirror the ByotHost's recorded
// version goes stale across an in-place upgrade. Best-effort against a
// missing host (cleared claim); a patch failure is returned so the reconcile
// retries the mirror.
func (r *ByotMachineReconciler) syncHostTalosVersion(
	ctx context.Context,
	byotMachine *infrav1.ByotMachine,
) error {
	if byotMachine.Status.ResolvedHost == "" || byotMachine.Status.CurrentTalosVersion == "" {
		return nil
	}

	host := &infrav1.ByotHost{}

	err := r.Client.Get(ctx, ctrlclient.ObjectKey{
		Namespace: byotMachine.Namespace,
		Name:      byotMachine.Status.ResolvedHost,
	}, host)
	if apierrors.IsNotFound(err) {
		return nil
	}

	if err != nil {
		return fmt.Errorf("failed to get ByotHost %s for version mirror: %w",
			byotMachine.Status.ResolvedHost, err)
	}

	if host.Status.TalosVersion == byotMachine.Status.CurrentTalosVersion {
		return nil
	}

	host.Status.TalosVersion = byotMachine.Status.CurrentTalosVersion

	err = r.Client.Status().Update(ctx, host)
	if err != nil {
		return fmt.Errorf("failed to mirror Talos version onto ByotHost %s: %w", host.Name, err)
	}

	log.FromContext(ctx).Info("Mirrored Talos version onto ByotHost",
		"byotHost", host.Name, "talosVersion", byotMachine.Status.CurrentTalosVersion)

	return nil
}

func (r *ByotMachineReconciler) applyAndMarkAdopted(
	ctx context.Context,
	patchHelper *patch.Helper,
	machine *clusterv1.Machine,
	byotMachine *infrav1.ByotMachine,
	machineConfig []byte,
	configHash string,
) (ctrl.Result, error) {
	logger := log.FromContext(ctx)

	talosConfig, bundleMatch, result, err := r.resolveApplyAuth(ctx, patchHelper, machine, byotMachine)
	if err != nil {
		return ctrl.Result{}, err
	}

	if result != nil {
		return *result, nil
	}

	wasReady := byotMachine.Status.Ready

	// Gate the first adoption of a worker on the cluster control plane being
	// Ready; see awaitControlPlaneReady. Control-plane machines are not gated
	// (they bootstrap their own certs). The join preflight above already ran.
	if !wasReady {
		if result, handled, err := r.awaitControlPlaneReady(ctx, patchHelper, machine, byotMachine); handled {
			return result, err
		} else if err != nil {
			return ctrl.Result{}, err
		}
	}

	// Detect the system disk and inject machine.install.disk into the config
	// before applying. The Talos installer validates the machine config on
	// upgrade and requires install.disk or diskSelector; cabpt sets neither, so
	// BYOT auto-detects it. Best-effort: on failure, fall through to the apply
	// (the upgrade will surface the validation error if the disk is truly
	// unset) rather than blocking adoption.
	disk, diskErr := detectSystemDisk(ctx, byotMachine.Status.ResolvedPublicIP, talosConfig)
	if diskErr != nil {
		logger.Info("could not detect system disk; applying config without machine.install.disk",
			"byotMachine", byotMachine.Name, "publicIP", byotMachine.Status.ResolvedPublicIP, "error", diskErr)
	} else {
		machineConfig, err = injectInstallDisk(machineConfig, disk)
		if err != nil {
			return ctrl.Result{}, r.recordApplyFailure(ctx, patchHelper, byotMachine, err)
		}
	}

	err = r.applyMachineConfig(ctx, byotMachine.Status.ResolvedPublicIP, machineConfig, talosConfig)
	if err != nil {
		return ctrl.Result{}, r.recordApplyFailure(ctx, patchHelper, byotMachine, err)
	}

	// Best-effort kubelet re-registration nudge for a bundleMatch re-adopt: the
	// machine keeps its config and datastore, the Node may have been deleted by
	// Cluster API, and the kubelet only re-registers it on restart. It runs
	// solely when the machine was adopted via an authenticated apply (bundleMatch)
	// on a not-yet-ready ByotMachine: a re-apply on an already-ready machine needs
	// no restart, and a fresh maintenance-mode adoption reboots so the kubelet
	// starts on boot.
	//
	// The nudge only restarts a kubelet that is already Running.
	//
	// Its failure never reverts a successful adoption: the configuration
	// apply already succeeded and the kubelet (re)starts on boot. A
	// transient failure (machine rebooting after its first apply, service
	// not yet defined) is recorded as a warning and self-heals when the
	// kubelet comes up.
	nudgeKubeletAfterReadopt(ctx, byotMachine, talosConfig, bundleMatch, wasReady, serviceRunning, restartService)

	markAdopted(byotMachine, configHash)

	err = patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, fmt.Errorf("failed to patch ByotMachine: %w", err)
	}

	logger.Info("Machine adopted", "byotMachine", byotMachine.Name, "publicIP", byotMachine.Status.ResolvedPublicIP)

	// Drive the post-adoption upgrade-then-link path in the same reconcile so
	// a freshly-adopted host upgrades (reboots) before it is linked and goes
	// live; see reconcileAdopted.
	return r.reconcileAdopted(ctx, patchHelper, byotMachine, machine)
}

// linkNode drives the Machine<->Node linkage for an adopted machine: first
// patch the workload Node's providerID (byot has no CCM, so the controller
// owns it), then retrigger the owning CAPI Machine's node-link reconciliation
// until status.nodeRef is set. updateNodeProviderID runs once (gated by
// status.nodeUpdated); ensureNodeLinked keeps retriggerring until the link
// completes. A requeue from either step short-circuits the other, which is
// fine since both re-run on the next reconcile.
func (r *ByotMachineReconciler) linkNode(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	machine *clusterv1.Machine,
) (ctrl.Result, error) {
	result, err := r.updateNodeProviderID(ctx, patchHelper, byotMachine, machine)
	if err != nil {
		return result, err
	}

	if result.Requeue || result.RequeueAfter > 0 {
		return result, nil
	}

	return r.ensureNodeLinked(ctx, patchHelper, byotMachine, machine)
}

// errWorkloadNodePending signals the workload Node is not registered yet;
// the kubelet registers it on boot. updateNodeProviderID requeues on it.
var errWorkloadNodePending = errors.New("workload node not registered")

// updateNodeProviderID patches the workload cluster Node's spec.providerID to
// byot://<resolvedPublicIP> so CAPI's Machine controller can link the Machine
// to its Node. byot has no cloud-controller-manager, so unlike cloud providers
// the controller owns the Machine<->Node providerID linkage: the kubelet
// reports an empty providerID (the host-registry model resolves the IP at
// claim time, so neither the chart nor CABPT can bake it into the config), so
// CAPI's Machine.spec.providerID <-> Node.spec.providerID match never fires
// and status.nodeRef is never set. Mirrors the kubevirt provider
// (KubevirtMachineReconciler.updateNodeProviderID). Gated by
// status.nodeUpdated so it runs once. When no ClusterCache is wired it is a
// no-op and ensureNodeLinked's retrigger annotation is the fallback.
func (r *ByotMachineReconciler) updateNodeProviderID(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	machine *clusterv1.Machine,
) (ctrl.Result, error) {
	if byotMachine.Status.NodeUpdated || byotMachine.Spec.ProviderID == nil {
		return ctrl.Result{}, nil
	}

	if r.getWorkloadClient == nil {
		// No ClusterCache wired (unit tests, or provider run standalone).
		// ensureNodeLinked's retrigger annotation is the fallback.
		return ctrl.Result{}, nil
	}

	clusterKey := ctrlclient.ObjectKey{
		Namespace: byotMachine.Namespace,
		Name:      machine.Spec.ClusterName,
	}

	workloadClient, err := r.getWorkloadClient(ctx, clusterKey)

	if errors.Is(err, clustercache.ErrClusterNotConnected) {
		// Workload API not up yet (control-plane bootstrap race). Requeue;
		// ensureNodeLinked's retrigger also compensates.
		return ctrl.Result{RequeueAfter: requeueAfterNodeLink}, nil
	}

	if err != nil {
		return ctrl.Result{}, fmt.Errorf("failed to get workload cluster client for %s: %w", clusterKey, err)
	}

	_, pErr := r.patchWorkloadNode(ctx, workloadClient, byotMachine, *byotMachine.Spec.ProviderID)
	if pErr != nil {
		if errors.Is(pErr, errWorkloadNodePending) {
			// Node not registered yet; the kubelet registers on boot. Requeue.
			return ctrl.Result{RequeueAfter: requeueAfterNodeLink}, nil
		}

		return ctrl.Result{}, pErr
	}

	byotMachine.Status.NodeUpdated = true

	err = patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, fmt.Errorf("failed to patch ByotMachine after Node providerID update: %w", err)
	}

	log.FromContext(ctx).Info("Patched workload Node providerID",
		"byotMachine", byotMachine.Name, "machine", machine.Name)

	return ctrl.Result{}, nil
}

// patchWorkloadNode gets the workload Node named after the ByotMachine
// (CABPT sets hostname.source=InfrastructureName, so the Node name equals
// the infrastructureRef name == ByotMachine.Name) and patches its
// spec.providerID when it does not already match. It returns alreadySet=true
// when the Node already carries the providerID (a prior run), so the caller
// marks status.nodeUpdated without a redundant patch. errWorkloadNodePending
// means the Node is not registered yet.
func (r *ByotMachineReconciler) patchWorkloadNode(
	ctx context.Context,
	workloadClient ctrlclient.Client,
	byotMachine *infrav1.ByotMachine,
	providerID string,
) (bool, error) {
	node := &corev1.Node{}

	err := workloadClient.Get(ctx, ctrlclient.ObjectKey{Name: byotMachine.Name}, node)
	if err != nil {
		if apierrors.IsNotFound(err) {
			return false, errWorkloadNodePending
		}

		return false, fmt.Errorf("failed to get workload Node %s: %w", byotMachine.Name, err)
	}

	if node.Spec.ProviderID == providerID {
		return true, nil
	}

	// Patch the Node providerID. Usually a cloud-controller-manager does
	// this, but byot has no CCM.
	patchBytes := fmt.Sprintf(`{"spec":{"providerID":%q}}`, providerID)
	mergePatch := ctrlclient.RawPatch(types.MergePatchType, []byte(patchBytes))

	err = workloadClient.Patch(ctx, node, mergePatch)
	if err != nil {
		return false, fmt.Errorf("failed to patch workload Node %s providerID: %w", byotMachine.Name, err)
	}

	return false, nil
}

// ensureNodeLinked retriggers the owning CAPI Machine's node-link
// reconciliation until the Machine reports status.nodeRef. An adopted
// ByotMachine has spec.providerID set, and the CAPI Machine controller links
// the workload Node by matching that providerID. On the control plane the
// workload API is down while the Machine controller first reconciles, so its
// node watch can miss the control-plane Node registering and the Machine
// stalls on "Waiting for a node with matching ProviderID". Bumping
// nodeLinkRetriggerAnnotation changes the ByotMachine object, which the
// Machine controller watches, forcing a re-list of workload nodes until the
// link completes. Once nodeRef is set the annotation is cleared and the
// requeue stops.
func (r *ByotMachineReconciler) ensureNodeLinked(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	machine *clusterv1.Machine,
) (ctrl.Result, error) {
	if !byotMachine.Status.Ready || byotMachine.Spec.ProviderID == nil {
		return ctrl.Result{}, nil
	}

	latest := &clusterv1.Machine{}

	err := r.Client.Get(ctx, ctrlclient.ObjectKeyFromObject(machine), latest)
	if err != nil {
		return ctrl.Result{}, fmt.Errorf("failed to get owner Machine %s: %w", machine.Name, err)
	}

	if latest.Status.NodeRef != nil {
		if _, ok := byotMachine.Annotations[nodeLinkRetriggerAnnotation]; ok {
			delete(byotMachine.Annotations, nodeLinkRetriggerAnnotation)

			err := patchHelper.Patch(ctx, byotMachine)
			if err != nil {
				return ctrl.Result{}, fmt.Errorf("failed to patch ByotMachine after clearing node-link annotation: %w", err)
			}
		}

		return ctrl.Result{}, nil
	}

	if byotMachine.Annotations == nil {
		byotMachine.Annotations = map[string]string{}
	}

	byotMachine.Annotations[nodeLinkRetriggerAnnotation] = strconv.FormatInt(time.Now().UnixNano(), 10)

	err = patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, fmt.Errorf("failed to patch ByotMachine with node-link retrigger: %w", err)
	}

	log.FromContext(ctx).Info("Retriggering Machine node-link",
		"byotMachine", byotMachine.Name, "machine", machine.Name)

	return ctrl.Result{RequeueAfter: requeueAfterNodeLink}, nil
}

// nudgeKubeletAfterReadopt restarts the kubelet so a Node deleted during a
// bundleMatch re-adopt re-registers, when the machine was re-adopted via an
// authenticated apply (bundleMatch) on a not-yet-ready ByotMachine. The restart
// is best-effort: its failure is recorded as a warning condition and never
// reverts the adoption, because the configuration apply already succeeded and
// the kubelet (re)starts on boot regardless. A fresh maintenance-mode adoption
// is excluded by the running probe: its kubelet starts on boot, and restarting
// a not-yet-running service would only record a spurious warning. running and
// restart are injected so the non-fatal path is unit-testable without a live
// Talos API.
func nudgeKubeletAfterReadopt(
	ctx context.Context,
	byotMachine *infrav1.ByotMachine,
	talosConfig []byte,
	bundleMatch bool,
	wasReady bool,
	running func(context.Context, string, []byte, string) (bool, error),
	restart func(context.Context, string, []byte, string) error,
) {
	logger := log.FromContext(ctx)

	if !bundleMatch || wasReady {
		return
	}

	// Only restart a kubelet that is already Running.
	isRunning, err := running(ctx, byotMachine.Status.ResolvedPublicIP, talosConfig, kubeletServiceID)
	if err != nil {
		// A probe failure is non-fatal: the kubelet registers on boot
		// regardless. Record nothing to avoid a spurious condition.
		logger.Info("Skipping kubelet restart nudge; service probe failed (non-fatal)",
			"byotMachine", byotMachine.Name,
			"publicIP", byotMachine.Status.ResolvedPublicIP,
			"error", err.Error())

		return
	}

	if !isRunning {
		logger.Info("Skipping kubelet restart nudge; kubelet not yet running (will register on boot)",
			"byotMachine", byotMachine.Name,
			"publicIP", byotMachine.Status.ResolvedPublicIP)

		return
	}

	err = restart(ctx, byotMachine.Status.ResolvedPublicIP, talosConfig, kubeletServiceID)
	if err != nil {
		conditions.MarkFalse(
			byotMachine,
			KubeletRestartNudgeCondition,
			"RestartFailed",
			clusterv1.ConditionSeverityWarning,
			"%s",
			err.Error(),
		)

		logger.Info("Kubelet restart nudge failed (non-fatal); kubelet registers on boot",
			"byotMachine", byotMachine.Name,
			"publicIP", byotMachine.Status.ResolvedPublicIP,
			"error", err.Error())

		return
	}

	conditions.MarkTrue(byotMachine, KubeletRestartNudgeCondition)

	logger.Info("Kubelet restarted after re-adoption",
		"byotMachine", byotMachine.Name,
		"publicIP", byotMachine.Status.ResolvedPublicIP)
}

// reconcileDelete releases the claimed ByotHost. Release always resets the
// host (STATE + EPHEMERAL) back to maintenance so it returns to the registry
// for re-claim; the ByotHost liveness loop flips Releasing → Available once
// maintenance answers. Deletion blocks until the reset is issued. A
// ByotMachine that never claimed a host is removed immediately.
func (r *ByotMachineReconciler) reconcileDelete(
	ctx context.Context,
	byotMachine *infrav1.ByotMachine,
) (ctrl.Result, error) {
	logger := log.FromContext(ctx)

	if !controllerutil.ContainsFinalizer(byotMachine, byotMachineFinalizer) {
		return ctrl.Result{}, nil
	}

	if byotMachine.Status.ResolvedHost != "" {
		err := r.releaseHost(ctx, byotMachine)
		if err != nil {
			logger.Info("Release reset failed, retrying",
				"byotMachine", byotMachine.Name,
				"byotHost", byotMachine.Status.ResolvedHost,
				"publicIP", byotMachine.Status.ResolvedPublicIP,
				"error", err.Error())

			return ctrl.Result{RequeueAfter: requeueAfterResetIssued}, nil
		}

		logger.Info("Host reset to maintenance and released",
			"byotMachine", byotMachine.Name,
			"byotHost", byotMachine.Status.ResolvedHost,
			"publicIP", byotMachine.Status.ResolvedPublicIP)
	} else {
		logger.Info("Machine released (no claimed host)",
			"byotMachine", byotMachine.Name)
	}

	if controllerutil.RemoveFinalizer(byotMachine, byotMachineFinalizer) {
		err := r.Client.Update(ctx, byotMachine)
		if err != nil {
			return ctrl.Result{}, fmt.Errorf("failed to remove finalizer from ByotMachine %s: %w", byotMachine.Name, err)
		}
	}

	return ctrl.Result{}, nil
}

// attemptReset tries each credential candidate (a nil candidate selects the
// insecure maintenance client) and returns the last error if all fail.
func attemptReset(ctx context.Context, candidates [][]byte, publicIP string) error {
	var lastErr error

	for _, candidate := range candidates {
		err := resetMachine(ctx, publicIP, candidate)
		if err == nil {
			return nil
		}

		lastErr = err
	}

	if lastErr != nil {
		return fmt.Errorf("failed to reset machine %s with any available credentials: %w", publicIP, lastErr)
	}

	return fmt.Errorf("%w: %s", ErrNoResetCredentials, publicIP)
}

// resetCredentialCandidates returns talosconfig candidates for the reset, in
// priority order, terminated by a nil entry which selects the insecure
// (maintenance) client.
func (r *ByotMachineReconciler) resetCredentialCandidates(
	ctx context.Context,
	byotMachine *infrav1.ByotMachine,
) ([][]byte, error) {
	candidates := [][]byte{}

	if byotMachine.Spec.TalosConfigSecretRef != nil {
		talosConfig, err := r.referencedTalosConfig(ctx, byotMachine.Spec.TalosConfigSecretRef.Name, byotMachine.Namespace)
		if err != nil && !errors.Is(err, ErrClusterTalosConfigNotReady) {
			return nil, fmt.Errorf("failed to load referenced talosconfig: %w", err)
		}

		if err == nil {
			candidates = append(candidates, talosConfig)
		}
	}

	clusterName := byotMachine.Labels[clusterNameLabel]
	if clusterName != "" {
		talosConfig, err := r.clusterTalosConfig(ctx, clusterName, byotMachine.Namespace)
		if err != nil && !errors.Is(err, ErrClusterTalosConfigNotReady) {
			return nil, fmt.Errorf("failed to load cluster talosconfig: %w", err)
		}

		if err == nil {
			candidates = append(candidates, talosConfig)
		}
	}

	return append(candidates, nil), nil
}

// adoptionInputs resolves the owner Machine and its bootstrap data. A non-nil
// wait result means one of them is not available yet; the caller should
// requeue with it.
func (r *ByotMachineReconciler) adoptionInputs(
	ctx context.Context,
	byotMachine *infrav1.ByotMachine,
) (*clusterv1.Machine, []byte, *ctrl.Result, error) {
	logger := log.FromContext(ctx)

	machine, err := util.GetOwnerMachine(ctx, r.Client, byotMachine.ObjectMeta)
	if err != nil {
		return nil, nil, nil, fmt.Errorf("failed to get owner Machine: %w", err)
	}

	if machine == nil {
		logger.Info("Waiting for Machine controller to set OwnerReference", "byotMachine", byotMachine.Name)

		return nil, nil, &ctrl.Result{RequeueAfter: requeueAfterBootstrap}, nil
	}

	machineConfig, err := r.bootstrapData(ctx, machine)
	if errors.Is(err, ErrBootstrapDataNotReady) {
		logger.Info("Waiting for bootstrap data", "byotMachine", byotMachine.Name, "machine", machine.Name)

		return nil, nil, &ctrl.Result{RequeueAfter: requeueAfterBootstrap}, nil
	}

	if err != nil {
		return nil, nil, nil, err
	}

	return machine, machineConfig, nil, nil
}

// recordApplyFailure marks the adoption condition false, persists it, and
// returns the apply error as the reconcile failure.
func (r *ByotMachineReconciler) recordApplyFailure(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	applyErr error,
) error {
	conditions.MarkFalse(
		byotMachine,
		MachineAdoptedCondition,
		"ApplyFailed",
		clusterv1.ConditionSeverityWarning,
		"%s",
		applyErr.Error(),
	)

	err := patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return fmt.Errorf("failed to patch ByotMachine after apply failure: %w", err)
	}

	return applyErr
}

// markAdopted updates the ByotMachine spec and status after a successful
// machine configuration apply.
func markAdopted(byotMachine *infrav1.ByotMachine, configHash string) {
	providerID := infrav1.ProviderIDPrefix + byotMachine.Status.ResolvedPublicIP

	byotMachine.Spec.ProviderID = &providerID
	byotMachine.Status.Ready = true
	byotMachine.Status.LastAppliedConfigSHA = configHash
	byotMachine.Status.Addresses = []clusterv1.MachineAddress{
		{
			Type:    clusterv1.MachineExternalIP,
			Address: byotMachine.Status.ResolvedPublicIP,
		},
	}

	conditions.MarkTrue(byotMachine, MachineAdoptedCondition)
}

// configUnchanged reports whether the machine is already adopted with the
// same configuration that would be applied now.
func configUnchanged(byotMachine *infrav1.ByotMachine, configHash string) bool {
	return byotMachine.Status.Ready &&
		byotMachine.Spec.ProviderID != nil &&
		byotMachine.Status.LastAppliedConfigSHA == configHash
}

func sha256Hex(data []byte) string {
	sum := sha256.Sum256(data)

	return hex.EncodeToString(sum[:])
}

// ownedTalosVersionReady is the patch option declaring TalosVersionReady as
// owned by this controller, so the upgrade-failure path can overwrite the
// condition even when its patch helper's base predates the issue-time
// "Upgrading" condition (avoids a 3-way merge conflict).
func ownedTalosVersionReady() patch.Option {
	return patch.WithOwnedConditions{Conditions: []clusterv1.ConditionType{TalosVersionReadyCondition}}
}

// bootstrapData reads the Talos machine configuration produced by the
// bootstrap provider for the given Machine.
func (r *ByotMachineReconciler) bootstrapData(
	ctx context.Context,
	machine *clusterv1.Machine,
) ([]byte, error) {
	if machine.Spec.Bootstrap.DataSecretName == nil {
		return nil, ErrBootstrapDataNotReady
	}

	secret := &corev1.Secret{}
	secretKey := ctrlclient.ObjectKey{
		Namespace: machine.Namespace,
		Name:      *machine.Spec.Bootstrap.DataSecretName,
	}

	err := r.Client.Get(ctx, secretKey, secret)
	if err != nil {
		if apierrors.IsNotFound(err) {
			return nil, ErrBootstrapDataNotReady
		}

		return nil, fmt.Errorf("failed to get bootstrap secret %s: %w", secretKey, err)
	}

	data, ok := secret.Data[bootstrapSecretDataKey]
	if !ok || len(data) == 0 {
		return nil, ErrBootstrapDataEmpty
	}

	return data, nil
}

// preflightForeignMachine handles a machine that is neither in maintenance
// mode nor accepting the cluster's own talosconfig. When the machine provably
// answers with a referenced foreign talosconfig, the join preflight fails
// with a bundle mismatch; otherwise the referenced config (if any) is used
// for the apply attempt, preserving the previous behavior for unreachable
// machines.
func (r *ByotMachineReconciler) preflightForeignMachine(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
) ([]byte, *ctrl.Result, error) {
	logger := log.FromContext(ctx)

	if byotMachine.Spec.TalosConfigSecretRef == nil {
		// Configured machine without credentials: treat it as a bundle
		// mismatch, it cannot be joined without resetting it first.
		return nil, nil, r.recordPreflightFailure(ctx, patchHelper, byotMachine, "NoCredentials", ErrJoinNoCredentials)
	}

	talosConfig, err := r.referencedTalosConfig(ctx, byotMachine.Spec.TalosConfigSecretRef.Name, byotMachine.Namespace)
	if errors.Is(err, ErrClusterTalosConfigNotReady) {
		logger.Info("Waiting for referenced talosconfig secret", "byotMachine", byotMachine.Name)

		return nil, &ctrl.Result{RequeueAfter: requeueAfterBootstrap}, nil
	}

	if err != nil {
		return nil, nil, err
	}

	if r.probeAuthenticated(ctx, byotMachine.Status.ResolvedPublicIP, talosConfig) {
		return nil, nil, r.recordPreflightFailure(ctx, patchHelper, byotMachine, "BundleMismatch", ErrJoinBundleMismatch)
	}

	return talosConfig, nil, nil
}

// recordPreflightFailure marks the join preflight condition false, persists
// it, and returns the preflight error as the reconcile failure.
func (r *ByotMachineReconciler) recordPreflightFailure(
	ctx context.Context,
	patchHelper *patch.Helper,
	byotMachine *infrav1.ByotMachine,
	reason string,
	preflightErr error,
) error {
	conditions.MarkFalse(
		byotMachine,
		JoinPreflightCondition,
		reason,
		clusterv1.ConditionSeverityError,
		"%s",
		preflightErr.Error(),
	)

	err := patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return fmt.Errorf("failed to patch ByotMachine after join preflight failure: %w", err)
	}

	return preflightErr
}

// awaitControlPlaneReady gates the first adoption of a worker on the cluster
// control plane being Ready. A worker's apid cannot finish booting until
// trustd (on a CP node) signs its API server CSR; adopting a worker before the
// CP is up wedges apid (it dials controlPlaneEndpoint:50001 forever), leaving
// the host's machine API unreachable and impossible to reset on release.
// Control-plane machines bootstrap their own certs and are not gated. Returns
// handled=true with a requeue when still waiting; handled=false to proceed.
func (r *ByotMachineReconciler) awaitControlPlaneReady(
	ctx context.Context,
	patchHelper *patch.Helper,
	machine *clusterv1.Machine,
	byotMachine *infrav1.ByotMachine,
) (ctrl.Result, bool, error) {
	if _, isControlPlane := machine.Labels[clusterv1.MachineControlPlaneLabel]; isControlPlane {
		return ctrl.Result{}, false, nil
	}

	ready, err := r.clusterControlPlaneReady(ctx, machine.Spec.ClusterName, byotMachine.Namespace)
	if err != nil {
		return ctrl.Result{}, false, err
	}

	if ready {
		return ctrl.Result{}, false, nil
	}

	conditions.MarkFalse(byotMachine, MachineAdoptedCondition, "WaitingForControlPlane",
		clusterv1.ConditionSeverityInfo,
		"worker adoption is gated on the cluster control plane being Ready")

	err = patchHelper.Patch(ctx, byotMachine)
	if err != nil {
		return ctrl.Result{}, false, fmt.Errorf("failed to patch ByotMachine: %w", err)
	}

	log.FromContext(ctx).Info("Waiting for control plane to be Ready before adopting worker",
		"byotMachine", byotMachine.Name, "cluster", machine.Spec.ClusterName)

	return ctrl.Result{RequeueAfter: requeueAfterBootstrap}, true, nil
}

// clusterControlPlaneReady reports whether the Cluster's control plane is
// Ready (conditions.ControlPlaneReady True). The condition is set by the
// control plane provider (e.g. TalosControlPlane). A worker is gated on it
// so its apid can obtain certs from trustd on a live CP; see adopt.
func (r *ByotMachineReconciler) clusterControlPlaneReady(
	ctx context.Context,
	clusterName string,
	namespace string,
) (bool, error) {
	cluster := &clusterv1.Cluster{}

	err := r.Client.Get(ctx, ctrlclient.ObjectKey{Name: clusterName, Namespace: namespace}, cluster)
	if apierrors.IsNotFound(err) {
		return false, nil
	}

	if err != nil {
		return false, fmt.Errorf("failed to get Cluster %s/%s: %w", namespace, clusterName, err)
	}

	return conditions.IsTrue(cluster, clusterv1.ControlPlaneReadyCondition), nil
}

// clusterTalosConfig loads the talosconfig generated by the bootstrap provider
// for the given cluster (secret "<cluster>-talosconfig").
func (r *ByotMachineReconciler) clusterTalosConfig(
	ctx context.Context,
	clusterName string,
	namespace string,
) ([]byte, error) {
	return r.referencedTalosConfig(ctx, clusterName+clusterTalosConfigSecretSuffix, namespace)
}

// referencedTalosConfig loads a talosconfig document from a secret in the
// same namespace. A missing secret is treated as a not-ready state.
func (r *ByotMachineReconciler) referencedTalosConfig(
	ctx context.Context,
	secretName string,
	namespace string,
) ([]byte, error) {
	secret := &corev1.Secret{}
	secretKey := ctrlclient.ObjectKey{
		Namespace: namespace,
		Name:      secretName,
	}

	err := r.Client.Get(ctx, secretKey, secret)
	if err != nil {
		if apierrors.IsNotFound(err) {
			return nil, ErrClusterTalosConfigNotReady
		}

		return nil, fmt.Errorf("failed to get talosconfig secret %s: %w", secretKey, err)
	}

	data, ok := secret.Data[talosConfigSecretDataKey]
	if !ok || len(data) == 0 {
		return nil, ErrClusterTalosConfigNotReady
	}

	return data, nil
}
